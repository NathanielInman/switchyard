#!/usr/bin/env python3
"""Writes the Homebrew formula, the Scoop manifest and the AUR PKGBUILD for a
release. Run by the release workflow:

    render.py VERSION SHA_MAC_ARM SHA_MAC_X86 SHA_LINUX_X86 SHA_LINUX_ARM SHA_WIN_X86 SHA_SOURCE
"""

import json
import pathlib
import sys

REPO = "NathanielInman/switchyard"
DESC = "A dispatch board for the scripts you keep writing"
ROOT = pathlib.Path(__file__).resolve().parent.parent


def main() -> None:
    version, mac_arm, mac_x86, lin_x86, lin_arm, win_x86, src = sys.argv[1:8]
    base = f"https://github.com/{REPO}/releases/download/v{version}"

    formula = f'''# Generated by packaging/render.py on release; edits here are overwritten.
class Switchyard < Formula
  desc "{DESC}"
  homepage "https://github.com/{REPO}"
  version "{version}"
  license "MIT"

  on_macos do
    if Hardware::CPU.arm?
      url "{base}/switchyard-aarch64-apple-darwin.tar.gz"
      sha256 "{mac_arm}"
    else
      url "{base}/switchyard-x86_64-apple-darwin.tar.gz"
      sha256 "{mac_x86}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "{base}/switchyard-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "{lin_arm}"
    else
      url "{base}/switchyard-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "{lin_x86}"
    end
  end

  def install
    bin.install "yard"
    bin.install "yard-tray" if File.exist?("yard-tray")
    bin.install "yard-board" if File.exist?("yard-board")
  end

  def caveats
    <<~EOS
      Start Switchyard at login and write a starter config:
        yard setup
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/yard version")
  end
end
'''
    (ROOT / "Formula").mkdir(exist_ok=True)
    (ROOT / "Formula" / "switchyard.rb").write_text(formula)

    scoop = {
        "version": version,
        "description": DESC,
        "homepage": f"https://github.com/{REPO}",
        "license": "MIT",
        "architecture": {
            "64bit": {
                "url": f"{base}/switchyard-x86_64-pc-windows-msvc.zip",
                "hash": win_x86,
            }
        },
        "bin": ["yard.exe", "yard-tray.exe"],
        "notes": "Run `yard setup` to start Switchyard at login and write a starter config.",
        "checkver": "github",
        "autoupdate": {
            "architecture": {
                "64bit": {
                    "url": f"https://github.com/{REPO}/releases/download/v$version/switchyard-x86_64-pc-windows-msvc.zip"
                }
            }
        },
    }
    (ROOT / "bucket").mkdir(exist_ok=True)
    (ROOT / "bucket" / "switchyard.json").write_text(json.dumps(scoop, indent=2) + "\n")

    pkgbuild = f'''# Maintainer: Nathaniel Inman <nate@theoestudio.com>
# Generated by packaging/render.py on release.
pkgname=switchyard
pkgver={version}
pkgrel=1
pkgdesc="{DESC}"
arch=('x86_64' 'aarch64')
url="https://github.com/{REPO}"
license=('MIT')
depends=('gtk4' 'gtk4-layer-shell' 'gcc-libs' 'glibc')
optdepends=('libnotify: failure notifications'
            'git: repo badges on the board')
makedepends=('cargo')
source=("$pkgname-$pkgver.tar.gz::$url/archive/v$pkgver.tar.gz")
sha256sums=('{src}')

prepare() {{
  cd "$pkgname-$pkgver"
  export RUSTUP_TOOLCHAIN=stable
  cargo fetch --locked --target "$(rustc -vV | sed -n 's/host: //p')"
}}

build() {{
  cd "$pkgname-$pkgver"
  export RUSTUP_TOOLCHAIN=stable
  export CARGO_TARGET_DIR=target
  cargo build --frozen --release -p yard -p yard-board
}}

check() {{
  cd "$pkgname-$pkgver"
  export RUSTUP_TOOLCHAIN=stable
  cargo test --frozen -p yard-core
}}

package() {{
  cd "$pkgname-$pkgver"
  install -Dm755 target/release/yard "$pkgdir/usr/bin/yard"
  install -Dm755 target/release/yard-board "$pkgdir/usr/bin/yard-board"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 README.md "$pkgdir/usr/share/doc/$pkgname/README.md"
  install -Dm644 docs/design.md "$pkgdir/usr/share/doc/$pkgname/design.md"
}}
'''
    srcinfo = f'''pkgbase = switchyard
\tpkgdesc = {DESC}
\tpkgver = {version}
\tpkgrel = 1
\turl = https://github.com/{REPO}
\tarch = x86_64
\tarch = aarch64
\tlicense = MIT
\tmakedepends = cargo
\tdepends = gtk4
\tdepends = gtk4-layer-shell
\tdepends = gcc-libs
\tdepends = glibc
\toptdepends = libnotify: failure notifications
\toptdepends = git: repo badges on the board
\tsource = switchyard-{version}.tar.gz::https://github.com/{REPO}/archive/v{version}.tar.gz
\tsha256sums = {src}

pkgname = switchyard
'''
    aur = ROOT / "packaging" / "aur"
    aur.mkdir(parents=True, exist_ok=True)
    (aur / "PKGBUILD").write_text(pkgbuild)
    (aur / ".SRCINFO").write_text(srcinfo)


if __name__ == "__main__":
    main()
